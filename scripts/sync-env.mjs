// Copies the root .env to the places each app reads from:
//   apps/api/.env        full copy (api + worker)
//   apps/web/.env.local  NEXT_PUBLIC_* lines only (never server secrets)
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { resolve } from 'node:path';

const root = resolve(new URL('..', import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, '$1'));
const src = resolve(root, '.env');
if (!existsSync(src)) {
  console.error('No .env at repo root. Copy .env.example to .env first.');
  process.exit(1);
}
const content = readFileSync(src, 'utf8');
writeFileSync(resolve(root, 'apps/api/.env'), content);
const publicLines = content
  .split(/\r?\n/)
  .filter((l) => /^NEXT_PUBLIC_[A-Z0-9_]+=/.test(l))
  .join('\n');
writeFileSync(
  resolve(root, 'apps/web/.env.local'),
  `# Generated by scripts/sync-env.mjs from the root .env — do not edit here.\n${publicLines}\n`,
);
console.log('synced .env -> apps/api/.env and apps/web/.env.local (public vars only)');
